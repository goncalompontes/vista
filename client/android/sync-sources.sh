#!/usr/bin/env bash
# Mirror the canonical iOS/portable sources into the Skip module.
# Run this after changing client/ios/Vista or client/core/Sources/VistaCore.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
dst="$here/Sources/Vista"

find "$dst" -maxdepth 1 -name '*.swift' ! -name 'SkipEntry.swift' -delete
cp "$repo"/client/core/Sources/VistaCore/*.swift "$dst"/
cp "$repo"/client/ios/Vista/Views/*.swift "$dst"/
sed -i '/^import VistaCore$/d' "$dst"/*.swift
for file in "$dst"/*.swift; do
    sed -i '1i // Generated by client/android/sync-sources.sh from the canonical iOS sources.' "$file"
done
echo "Synced $(find "$dst" -maxdepth 1 -name '*.swift' | wc -l) Swift files into $dst"
